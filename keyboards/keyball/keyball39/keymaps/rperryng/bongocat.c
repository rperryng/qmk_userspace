static uint8_t state = BONGOCAT_IDLE;

static void bongocat_sync_handler(uint8_t in_buflen, const void *in_data, uint8_t out_buflen, void *out_data) {
    if (in_buflen == sizeof(state)) {
        state = *(const uint8_t *)in_data;
    }
}

void bongocat_init(void) {
    if (!is_keyboard_master()) {
        transaction_register_rpc(USER_BONGOCAT_SYNC, bongocat_sync_handler);
    }
}

// Whether any key is held in the given half of the matrix. Rows 0..N/2-1 are
// always the left half, regardless of which side is master.
static bool half_held(bool left) {
    uint8_t start = left ? 0 : MATRIX_ROWS / 2;
    for (uint8_t row = start; row < start + MATRIX_ROWS / 2; row++) {
        if (matrix_get_row(row)) {
            return true;
        }
    }
    return false;
}

static bool paw_down(bool held, bool *was_held, uint16_t *pressed_at) {
    if (held && !*was_held) {
        *pressed_at = timer_read();
    }
    *was_held = held;
    return held || timer_elapsed(*pressed_at) < BONGOCAT_TAP_MS;
}

void bongocat_task(void) {
    if (!is_keyboard_master()) {
        return;
    }

    static bool     left_held, right_held;
    static uint16_t left_at, right_at;
    static uint32_t active_at;
    static uint16_t synced_at;
    static uint8_t  synced_state;

    uint8_t paws = (paw_down(half_held(true), &left_held, &left_at) ? PAW_LEFT : 0) |
                   (paw_down(half_held(false), &right_held, &right_at) ? PAW_RIGHT : 0);
    if (paws) {
        active_at = timer_read32();
    }
    state = paws ? paws : (timer_elapsed32(active_at) > BONGOCAT_IDLE_MS ? BONGOCAT_IDLE : 0);

    if (state != synced_state || timer_elapsed(synced_at) > BONGOCAT_SYNC_MS) {
        if (transaction_rpc_send(USER_BONGOCAT_SYNC, sizeof(state), &state)) {
            synced_state = state;
            synced_at    = timer_read();
        }
    }
}

void bongocat_render(void) {
    switch (state) {
        case BONGOCAT_IDLE: {
            // Ping-pong through the idle frames: 0 1 2 3 4 3 2 1 ...
            uint8_t step  = (timer_read32() / BONGOCAT_IDLE_FRAME_MS) % (2 * (BONGOCAT_IDLE_FRAMES - 1));
            uint8_t frame = step < BONGOCAT_IDLE_FRAMES ? step : 2 * (BONGOCAT_IDLE_FRAMES - 1) - step;
            oled_write_raw_P(bongocat_idle[frame], BONGOCAT_FRAME_SIZE);
            break;
        }
        case PAW_LEFT:
            oled_write_raw_P(bongocat_left, BONGOCAT_FRAME_SIZE);
            break;
        case PAW_RIGHT:
            oled_write_raw_P(bongocat_right, BONGOCAT_FRAME_SIZE);
            break;
        case PAW_LEFT | PAW_RIGHT:
            oled_write_raw_P(bongocat_both, BONGOCAT_FRAME_SIZE);
            break;
        default:
            oled_write_raw_P(bongocat_up, BONGOCAT_FRAME_SIZE);
            break;
    }
}
